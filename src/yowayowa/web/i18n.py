if set(_EN) != set(_JA):
    raise RuntimeError("Japanese and English translation catalogs must have identical keys")

_MESSAGES = {"en": _EN, "ja": _JA}


def resolve_locale(request: Request) -> str:
    query = request.query_params.get("lang")
    if query in SUPPORTED_LOCALES:
        return query
    cookie = request.cookies.get(LANGUAGE_COOKIE)
    if cookie in SUPPORTED_LOCALES:
        return cookie
    accepted = request.headers.get("accept-language", "").lower()
    for token in accepted.split(","):
        language = token.split(";", 1)[0].strip()
        if language.startswith("ja"):
            return "ja"
        if language.startswith("en"):
            return "en"
    return DEFAULT_LOCALE


def messages(locale: str) -> Mapping[str, str]:
    return _MESSAGES.get(locale, _MESSAGES[DEFAULT_LOCALE])


def translate(locale: str, key: str, **values: object) -> str:
    template = messages(locale).get(key) or _EN.get(key) or key
    return template.format(**values) if values else template
